/// `{ "mario": { "mJumpHeight": [22.0, null, 40.0] } }`: a null keeps the game's number at that place.
pub type Constants = BTreeMap<String, BTreeMap<String, Vec<Option<f64>>>>;

fn element_size(kind: u8) -> u32 {
    match kind {
        b'f' | b'i' => 4,
        b'H' | b'h' => 2,
        _ => 1,
    }
}

fn read_element(kind: u8, bytes: &[u8]) -> f64 {
    match kind {
        b'f' => f64::from(f32::from_be_bytes([bytes[0], bytes[1], bytes[2], bytes[3]])),
        b'i' => f64::from(i32::from_be_bytes([bytes[0], bytes[1], bytes[2], bytes[3]])),
        b'H' => f64::from(u16::from_be_bytes([bytes[0], bytes[1]])),
        b'h' => f64::from(i16::from_be_bytes([bytes[0], bytes[1]])),
        _ => f64::from(bytes[0]),
    }
}

/// Whether a name is a number of the table.
pub fn is_known(name: &str) -> bool {
    FIELDS.iter().any(|f| f.name == name)
}

pub fn field(name: &str) -> Option<&'static Field> {
    FIELDS.iter().find(|f| f.name == name)
}

/// A write over a table: which numbers it sets to what. None: not over a table, or not lying on whole numbers.
pub fn write(address: u32, value: &[u8]) -> Option<Constants> {
    let address = address | 0x8000_0000;
    let (who, offset) = if (MARIO_TABLE..MARIO_TABLE + TABLE_SIZE).contains(&address) {
        ("mario", address - MARIO_TABLE)
    } else if (LUIGI_TABLE..LUIGI_TABLE + TABLE_SIZE).contains(&address) {
        ("luigi", address - LUIGI_TABLE)
    } else {
        return None;
    };
    if value.is_empty() || offset + value.len() as u32 > TABLE_SIZE {
        return None;
    }
    let end = offset + value.len() as u32;
    let mut out: BTreeMap<String, Vec<Option<f64>>> = BTreeMap::new();
    let mut covered = 0u32;
    for field in FIELDS {
        let size = element_size(field.kind);
        for index in 0..field.count {
            let at = field.offset + index * size;
            if at + size <= offset || at >= end {
                continue;
            }
            if at < offset || at + size > end {
                return None;
            }
            let number = read_element(field.kind, &value[(at - offset) as usize..(at - offset + size) as usize]);
            let list = out.entry(field.name.to_string()).or_default();
            list.resize(index as usize + 1, None);
            list[index as usize] = Some(number);
            covered += size;
        }
    }
    // Padding between numbers is all that may be left over.
    if covered == 0 || covered + 8 < value.len() as u32 {
        return None;
    }
    Some(BTreeMap::from([(who.to_string(), out)]))
}

/// Adds `more` to `into`, later numbers replacing earlier ones.
pub fn merge(into: &mut Constants, more: Constants) {
    for (who, fields) in more {
        let mine = into.entry(who).or_default();
        for (name, list) in fields {
            let row = mine.entry(name).or_default();
            if row.len() < list.len() {
                row.resize(list.len(), None);
            }
            for (i, number) in list.into_iter().enumerate() {
                if number.is_some() {
                    row[i] = number;
                }
            }
        }
    }
}

